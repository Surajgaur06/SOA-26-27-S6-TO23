import io
import csv
from datetime import datetime, timezone
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.units import inch
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether, HRFlowable
)
from app.models.entities import CalibrationRecord

def generate_calibration_pdf(record: CalibrationRecord) -> bytes:
    """
    Generates an official, publication-quality, metrology-grade calibration certificate/report in PDF.
    Prominently displays educational/demo disclaimers as mandated by standard metrology governance.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )
    
    styles = getSampleStyleSheet()
    
    # Custom styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=18,
        leading=22,
        textColor=colors.HexColor('#0F172A'),
        fontName='Helvetica-Bold'
    )
    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#475569')
    )
    section_heading = ParagraphStyle(
        'SectionHeading',
        parent=styles['Heading2'],
        fontSize=12,
        leading=16,
        textColor=colors.HexColor('#1E293B'),
        fontName='Helvetica-Bold',
        spaceBefore=8,
        spaceAfter=4
    )
    table_cell = ParagraphStyle(
        'TableCell',
        parent=styles['Normal'],
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor('#1E293B')
    )
    table_cell_bold = ParagraphStyle(
        'TableCellBold',
        parent=styles['Normal'],
        fontSize=8.5,
        leading=11,
        fontName='Helvetica-Bold',
        textColor=colors.HexColor('#0F172A')
    )
    disclaimer_style = ParagraphStyle(
        'DisclaimerText',
        parent=styles['Normal'],
        fontSize=7.5,
        leading=10,
        textColor=colors.HexColor('#B45309')
    )
    
    elements = []
    
    # Header Banner
    header_data = [
        [
            Paragraph("<b>TempTrace Metrology Systems</b><br/><font size=8 color='#64748B'>Laboratory Information & Calibration Provenance</font>", styles['Normal']),
            Paragraph(f"<b>CALIBRATION CERTIFICATE</b><br/><font color='#0284C7'><b>Report ID: {record.record_number}</b></font>", ParagraphStyle('RAlign', parent=styles['Normal'], alignment=2))
        ]
    ]
    header_table = Table(header_data, colWidths=[4.0*inch, 3.5*inch])
    header_table.setStyle(TableStyle([
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
    ]))
    elements.append(header_table)
    elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#0284C7'), spaceBefore=2, spaceAfter=8))
    
    # Educational / Demo Banner
    banner_color = colors.HexColor('#FEF3C7')
    banner_text = (
        "<b>EDUCATIONAL & DEMONSTRATION CALIBRATION RECORD</b><br/>"
        "Notice: This calibration document is generated by TempTrace for demonstration, validation, and educational traceability tracking. "
        "It does not represent an ISO/IEC 17025 accredited certificate unless independently audited and authorized by an accredited calibration laboratory."
    )
    banner_table = Table([[Paragraph(banner_text, disclaimer_style)]], colWidths=[7.5*inch])
    banner_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), banner_color),
        ('BOX', (0,0), (-1,-1), 1, colors.HexColor('#F59E0B')),
        ('TOPPADDING', (0,0), (-1,-1), 6),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('LEFTPADDING', (0,0), (-1,-1), 8),
        ('RIGHTPADDING', (0,0), (-1,-1), 8),
    ]))
    elements.append(banner_table)
    elements.append(Spacer(1, 8))
    
    # Logger and Reference Metadata Grid
    logger = record.logger
    ref = record.reference_instrument
    tech = record.technician
    
    meta_data = [
        [
            Paragraph("<b>UNIT UNDER TEST (LOGGER)</b>", table_cell_bold),
            Paragraph("<b>REFERENCE INSTRUMENT & TRACEABILITY</b>", table_cell_bold)
        ],
        [
            Paragraph(
                f"<b>Logger ID:</b> {logger.logger_id if logger else 'N/A'}<br/>"
                f"<b>Manufacturer:</b> {logger.manufacturer if logger else 'N/A'}<br/>"
                f"<b>Model:</b> {logger.model if logger else 'N/A'}<br/>"
                f"<b>Serial No:</b> {logger.serial_number if logger else 'N/A'}<br/>"
                f"<b>Type:</b> {logger.logger_type if logger else 'N/A'}<br/>"
                f"<b>Range:</b> {logger.measurement_range if logger else 'N/A'}<br/>"
                f"<b>Location:</b> {logger.location if logger else 'N/A'}<br/>"
                f"<b>Owner:</b> {logger.owner if logger else 'N/A'}",
                table_cell
            ),
            Paragraph(
                f"<b>Ref ID:</b> {ref.instrument_id if ref else 'N/A'}<br/>"
                f"<b>Instrument:</b> {ref.manufacturer if ref else ''} {ref.model if ref else ''}<br/>"
                f"<b>Serial No:</b> {ref.serial_number if ref else 'N/A'}<br/>"
                f"<b>Cert No:</b> {ref.certificate_number if ref else 'N/A'}<br/>"
                f"<b>Provider:</b> {ref.calibration_provider if ref else 'N/A'}<br/>"
                f"<b>Expiry Date:</b> {ref.expiry_date.strftime('%Y-%m-%d') if ref and ref.expiry_date else 'N/A'}<br/>"
                f"<b>Stated Uncertainty:</b> {ref.stated_uncertainty if ref else 'N/A'}<br/>"
                f"<b>Traceability Chain:</b> {ref.traceability_details if ref else 'N/A'}",
                table_cell
            )
        ]
    ]
    meta_table = Table(meta_data, colWidths=[3.75*inch, 3.75*inch])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#F1F5F9')),
        ('BOX', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
        ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#E2E8F0')),
        ('TOPPADDING', (0,0), (-1,-1), 5),
        ('BOTTOMPADDING', (0,0), (-1,-1), 5),
        ('LEFTPADDING', (0,0), (-1,-1), 6),
        ('RIGHTPADDING', (0,0), (-1,-1), 6),
    ]))
    elements.append(meta_table)
    elements.append(Spacer(1, 8))
    
    # Calibration Conditions
    cond_data = [
        [
            Paragraph("<b>Calibration Date:</b>", table_cell),
            Paragraph(record.calibration_date.strftime('%Y-%m-%d %H:%M UTC') if record.calibration_date else "N/A", table_cell),
            Paragraph("<b>Ambient Conditions:</b>", table_cell),
            Paragraph(f"{record.ambient_temperature:.1f} °C / {record.ambient_humidity:.1f}% RH", table_cell)
        ],
        [
            Paragraph("<b>Technician:</b>", table_cell),
            Paragraph(tech.full_name if tech else "N/A", table_cell),
            Paragraph("<b>Procedure / SOP:</b>", table_cell),
            Paragraph(f"{record.procedure_code} ({record.tolerance_source})", table_cell)
        ],
        [
            Paragraph("<b>Location:</b>", table_cell),
            Paragraph(record.location, table_cell),
            Paragraph("<b>Acceptance Limit:</b>", table_cell),
            Paragraph(f"±{record.configured_tolerance:.2f} °C", table_cell)
        ]
    ]
    cond_table = Table(cond_data, colWidths=[1.5*inch, 2.25*inch, 1.5*inch, 2.25*inch])
    cond_table.setStyle(TableStyle([
        ('BOX', (0,0), (-1,-1), 0.5, colors.HexColor('#E2E8F0')),
        ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#F1F5F9')),
        ('TOPPADDING', (0,0), (-1,-1), 4),
        ('BOTTOMPADDING', (0,0), (-1,-1), 4),
        ('LEFTPADDING', (0,0), (-1,-1), 6),
    ]))
    elements.append(cond_table)
    elements.append(Spacer(1, 10))
    
    # Measurement Results Table
    elements.append(Paragraph("<b>MEASUREMENT RESULTS & ERROR ANALYSIS</b>", section_heading))
    
    table_headers = [
        Paragraph("<b>Pt</b>", table_cell_bold),
        Paragraph("<b>Nominal (°C)</b>", table_cell_bold),
        Paragraph("<b>Ref Reading (°C)</b>", table_cell_bold),
        Paragraph("<b>U(ref)</b>", table_cell_bold),
        Paragraph("<b>Logger Reading (°C)</b>", table_cell_bold),
        Paragraph("<b>Error (°C)</b>", table_cell_bold),
        Paragraph("<b>Tolerance</b>", table_cell_bold),
        Paragraph("<b>Outcome</b>", table_cell_bold),
    ]
    
    measure_rows = [table_headers]
    for pt in record.measurement_points:
        outcome_color = '#15803D' if pt.outcome.value == 'pass' else '#DC2626'
        measure_rows.append([
            Paragraph(str(pt.sequence), table_cell),
            Paragraph(f"{pt.nominal_temperature:.2f}", table_cell),
            Paragraph(f"{pt.reference_reading:.3f}", table_cell),
            Paragraph(f"±{pt.ref_uncertainty:.2f}" if pt.ref_uncertainty else "-", table_cell),
            Paragraph(f"{pt.logger_reading:.3f}", table_cell),
            Paragraph(f"{pt.error:+.3f}", table_cell),
            Paragraph(f"±{pt.allowed_tolerance:.2f}", table_cell),
            Paragraph(f"<font color='{outcome_color}'><b>{pt.outcome.value.upper()}</b></font>", table_cell)
        ])
    
    measure_table = Table(measure_rows, colWidths=[0.4*inch, 1.0*inch, 1.1*inch, 0.8*inch, 1.1*inch, 1.0*inch, 1.0*inch, 1.1*inch])
    measure_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#F8FAFC')),
        ('BOX', (0,0), (-1,-1), 0.5, colors.HexColor('#94A3B8')),
        ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#E2E8F0')),
        ('TOPPADDING', (0,0), (-1,-1), 4),
        ('BOTTOMPADDING', (0,0), (-1,-1), 4),
        ('ALIGN', (0,0), (-1,-1), 'CENTER'),
    ]))
    elements.append(measure_table)
    elements.append(Spacer(1, 8))
    
    # Overall Outcome & Provenance summary
    outcome_str = "PASS" if record.overall_outcome.value == "pass" else "FAIL"
    outcome_bg = colors.HexColor('#DCFCE7') if outcome_str == "PASS" else colors.HexColor('#FEE2E2')
    outcome_txt_color = '#166534' if outcome_str == "PASS" else '#991B1B'
    
    summary_data = [
        [
            Paragraph(
                f"<b>OVERALL CALIBRATION RESULT: </b>"
                f"<font color='{outcome_txt_color}' size=11><b>{outcome_str}</b></font><br/>"
                f"<font size=8 color='#475569'>Maximum Absolute Error: <b>{record.max_error:.4f} °C</b> | "
                f"Acceptance Limit: <b>±{record.configured_tolerance:.2f} °C</b></font>",
                table_cell
            )
        ]
    ]
    summary_table = Table(summary_data, colWidths=[7.5*inch])
    summary_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), outcome_bg),
        ('BOX', (0,0), (-1,-1), 1, colors.HexColor('#CBD5E1')),
        ('TOPPADDING', (0,0), (-1,-1), 6),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('LEFTPADDING', (0,0), (-1,-1), 8),
    ]))
    elements.append(summary_table)
    elements.append(Spacer(1, 10))
    
    # Provenance and Cryptographic Fingerprint
    elements.append(Paragraph("<b>DATA INTEGRITY & PROVENANCE FINGERPRINT</b>", section_heading))
    prov_text = (
        f"<b>Provenance Hash (SHA-256):</b> <font color='#0284C7' face='Courier'>{record.provenance_hash or 'UNFINALIZED_DRAFT'}</font><br/>"
        f"<b>Record State:</b> {record.state.value.upper()} (Version {record.version}) | "
        f"<b>Finalized At:</b> {record.finalized_at.strftime('%Y-%m-%d %H:%M UTC') if record.finalized_at else 'Pending'} | "
        f"<b>Generated:</b> {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}<br/>"
        f"<b>Notes:</b> {record.notes or 'None'}"
    )
    prov_table = Table([[Paragraph(prov_text, table_cell)]], colWidths=[7.5*inch])
    prov_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#F8FAFC')),
        ('BOX', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
        ('TOPPADDING', (0,0), (-1,-1), 6),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('LEFTPADDING', (0,0), (-1,-1), 8),
    ]))
    elements.append(prov_table)
    elements.append(Spacer(1, 14))
    
    # Signatures
    sig_data = [
        [
            Paragraph("<b>Calibrated By:</b><br/><br/>___________________________<br/>" + (tech.full_name if tech else "Calibration Technician"), table_cell),
            Paragraph("<b>Reviewed & Released By:</b><br/><br/>___________________________<br/>Quality Assurance / Metrologist", table_cell)
        ]
    ]
    sig_table = Table(sig_data, colWidths=[3.75*inch, 3.75*inch])
    sig_table.setStyle(TableStyle([
        ('TOPPADDING', (0,0), (-1,-1), 4),
        ('BOTTOMPADDING', (0,0), (-1,-1), 4),
    ]))
    elements.append(KeepTogether(sig_table))
    
    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()

def generate_calibration_csv(record: CalibrationRecord) -> str:
    """
    Generates standard comma-separated tabular data of calibration measurement points.
    """
    output = io.StringIO()
    writer = csv.writer(output)
    
    # Header block
    writer.writerow(["TempTrace Calibration Measurement Export"])
    writer.writerow(["Record Number", record.record_number])
    writer.writerow(["Logger ID", record.logger.logger_id if record.logger else ""])
    writer.writerow(["Logger Serial Number", record.logger.serial_number if record.logger else ""])
    writer.writerow(["Reference Instrument ID", record.reference_instrument.instrument_id if record.reference_instrument else ""])
    writer.writerow(["Reference Certificate", record.reference_instrument.certificate_number if record.reference_instrument else ""])
    writer.writerow(["Calibration Date", record.calibration_date.isoformat() if record.calibration_date else ""])
    writer.writerow(["Technician", record.technician.full_name if record.technician else ""])
    writer.writerow(["Configured Tolerance (°C)", record.configured_tolerance])
    writer.writerow(["Overall Outcome", record.overall_outcome.value])
    writer.writerow(["Provenance Hash", record.provenance_hash or ""])
    writer.writerow([])
    
    # Data columns
    writer.writerow([
        "Sequence", "Nominal (°C)", "Reference Reading (°C)", "Logger Reading (°C)", 
        "Reference Uncertainty", "Error (°C)", "Absolute Error (°C)", "Tolerance (°C)", "Outcome"
    ])
    
    for pt in record.measurement_points:
        writer.writerow([
            pt.sequence,
            pt.nominal_temperature,
            pt.reference_reading,
            pt.logger_reading,
            pt.ref_uncertainty,
            pt.error,
            pt.abs_error,
            pt.allowed_tolerance,
            pt.outcome.value
        ])
        
    return output.getvalue()
